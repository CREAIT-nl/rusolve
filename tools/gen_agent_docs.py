#!/usr/bin/env python3
"""Generates docs/agent/reference.md from the solver itself.

    python3 tools/gen_agent_docs.py            # rewrite docs/agent/reference.md
    python3 tools/gen_agent_docs.py --check    # exit 1 if the committed file is stale (CI / cargo test)

Sources, all read from the built binary ($RSV_CLI, else target/release/rusolve-cli):
  * options:    `rusolve options --json`  (the option registry, every HiGHS and rusolve option with ranges)
  * env vars:   `rusolve env --json`      (the environment-variable registry)
  * MCP tools:  `tools/list` of `rusolve mcp` (names, descriptions, input schemas)
  * commands:   `rusolve --help --json`: the command registry, with every flag's type,
                default and choices and the output schema. No hand-kept table remains: a command or
                flag added to the registry appears here on the next run, and the check fails until
                the committed file is regenerated.
Output is deterministic: no timestamps, versions or paths.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "agent", "reference.md")
DIAG_OUT = os.path.join(ROOT, "docs", "agent", "diagnostics.md")


EXIT_CODES = [
    ("0", "the command ran; the solve status is in the output, not in the code"),
    ("2", "usage error: unknown flag, missing value, bad `--opt`, unregistered `RUSOLVE_*` variable"),
    ("3", "input error: model file missing, unreadable or not parseable"),
    ("4", "internal error: the solver returned an error, or a requested output file could not be written"),
]


def binary():
    p = os.environ.get("RSV_CLI") or os.path.join(ROOT, "target", "release", "rusolve-cli")
    if not os.path.exists(p):
        sys.exit(f"gen_agent_docs: rusolve-cli not found at {p}; build it (cargo build --release -p rusolve-cli) "
                 "or set RSV_CLI")
    return p


def run(args, env=None):
    return subprocess.run([binary(), *args], capture_output=True, text=True, timeout=120,
                          env=dict(os.environ, **(env or {})))


def run_json(args):
    r = run(args)
    if r.returncode != 0:
        sys.exit(f"gen_agent_docs: rusolve-cli {' '.join(args)} exited {r.returncode}: {r.stderr.strip()[:300]}")
    return json.loads(r.stdout)


def mcp_tools():
    msgs = [
        {"jsonrpc": "2.0", "id": 1, "method": "initialize",
         "params": {"protocolVersion": "2025-11-25", "capabilities": {}, "clientInfo": {"name": "gen", "version": "1"}}},
        {"jsonrpc": "2.0", "method": "notifications/initialized"},
        {"jsonrpc": "2.0", "id": 2, "method": "tools/list"},
    ]
    r = subprocess.run([binary(), "mcp"], input="\n".join(map(json.dumps, msgs)) + "\n", capture_output=True,
                       text=True, timeout=60)
    for line in r.stdout.splitlines():
        d = json.loads(line)
        if d.get("id") == 2:
            return d["result"]["tools"]
    sys.exit("gen_agent_docs: `rusolve mcp` did not answer tools/list")


def commands_from_help_json():
    """`rusolve --help --json`, the command registry. Exits when it is unusable."""
    r = run(["--help", "--json"])
    if r.returncode != 0:
        sys.exit("gen_agent_docs: `rusolve --help --json` failed")
    d = json.loads(r.stdout)
    cmds = d.get("commands") if isinstance(d, dict) else None
    if not isinstance(cmds, list) or not cmds or any("name" not in c for c in cmds):
        sys.exit("gen_agent_docs: `rusolve --help --json` has no `commands` list")
    return cmds


def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def fmt_default(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    return "" if v is None else str(v)


def render():
    options = run_json(["options", "--json"])
    env = run_json(["env", "--json"])
    tools = mcp_tools()
    help_cmds = commands_from_help_json()
    o = []
    w = o.append
    w("# rusolve agent reference\n")
    w("<!-- GENERATED by tools/gen_agent_docs.py from the built binary. Do not edit; run the script. "
      "A test (crates/rusolve-cli/tests/agent_docs.rs) fails when this file is stale. -->\n")
    w("Start with [llms.txt](../../llms.txt) and the skills in [docs/skills](../skills). This page lists every "
      "command, MCP tool, option and environment variable the binary knows.\n")
    w("## Exit codes\n")
    w("| code | meaning |\n|---|---|")
    for c, m in EXIT_CODES:
        w(f"| {c} | {m} |")
    w("\nExit codes 2/3/4 apply on the port path (the default; `RUSOLVE_MIP_HIGHS=0` selects the native search) and the agent subcommands; the legacy "
      "native `solve` path still uses 0/1/2.\n")

    w("## Commands\n")
    w("Source: `rusolve --help --json`, the command registry that also drives `--help` and the option "
      "parser. `--format json` prints exactly one JSON object on stdout with a `schema_version`; logs go to "
      "stderr. Schemas live in `docs/schema/`.\n")
    w("| command | usage | what it does | output schema |\n|---|---|---|---|")
    for c in sorted(help_cmds, key=lambda c: c["name"]):
        sch = c.get("output_schema") or ""
        w(f"| `{c['name']}` | `{md_escape(c.get('usage', ''))}` | {md_escape(c.get('summary', ''))} | "
          f"{('`' + sch + '`') if sch else ''} |")
    w("")
    for c in sorted(help_cmds, key=lambda c: c["name"]):
        flags = c.get("flags") or []
        if not flags:
            continue
        w(f"### `rusolve {c['name']}` flags\n")
        w("| flag | value | default | choices | description |\n|---|---|---|---|---|")
        for f in flags:
            val = f.get("value") or ("" if f.get("type") == "switch" else f.get("type", ""))
            w(f"| `{f['name']}` | {md_escape(val)} | {md_escape(fmt_default(f.get('default')))} | "
              f"{md_escape(', '.join(f.get('choices') or []))} | {md_escape(f.get('description', ''))}"
              f"{' (repeatable)' if f.get('repeatable') else ''} |")
        w("")

    w("## MCP tools (`rusolve mcp`, stdio)\n")
    w("Config: `{\"mcpServers\": {\"rusolve\": {\"command\": \"/path/to/rusolve-cli\", \"args\": [\"mcp\"]}}}`. "
      "Every tool but `load_model` takes the `model_id` that `load_model` returns. Details: docs/design/mcp.md.\n")
    for t in tools:
        props = t.get("inputSchema", {}).get("properties", {})
        req = set(t.get("inputSchema", {}).get("required", []))
        w(f"### `{t['name']}`\n")
        w(md_escape(t.get("description", "")) + "\n")
        if props:
            w("| parameter | type | required | description |\n|---|---|---|---|")
            for p in sorted(props):
                spec = props[p]
                typ = spec.get("type", "")
                if isinstance(typ, list):
                    typ = "/".join(typ)
                w(f"| `{p}` | {typ} | {'yes' if p in req else ''} | {md_escape(spec.get('description', ''))} |")
            w("")

    w("## Options\n")
    w(f"{len(options)} options from `rusolve options --json` (the HiGHS option registry; set them with "
      "`--opt key=value`, `--options-file`, or the MCP `solve` tool's `options` map). `affects` says whether an "
      "option can change the search (`search`), only a tolerance (`tolerance`), only runtime behaviour "
      "(`runtime`) or only output (`output`). Run `rusolve options --json --non-default` to see what a run "
      "changed.\n")
    w("| option | type | default | range | affects | tunable | description |\n|---|---|---|---|---|---|---|")
    for op in sorted(options, key=lambda x: x["name"]):
        rng = ""
        if op.get("lower") is not None or op.get("upper") is not None:
            rng = f"[{fmt_default(op.get('lower'))}, {fmt_default(op.get('upper'))}]"
        w(f"| `{op['name']}` | {op['type_name']} | {md_escape(fmt_default(op.get('default')))} | {rng} | "
          f"{op.get('affects', '')} | {'yes' if op.get('tunable') else ''} | {md_escape(op.get('description', ''))} |")
    w("")

    w("## Environment variables\n")
    w(f"{len(env)} variables from `rusolve env --json`. Only `lever` and `profile` variables are for users: "
      "`harness` and `debug` ones exist for benchmarking and tracing. Prefer an option over a variable. "
      "An unregistered `RUSOLVE_*` name makes the CLI exit 2 with the nearest registered name.\n")
    w("| variable | kind | scope | values | what it does |\n|---|---|---|---|---|")
    for e in sorted(env, key=lambda x: x["name"]):
        w(f"| `{e['name']}` | {e['kind']} | {e['scope']} | {md_escape(e.get('values', ''))} | {md_escape(e.get('doc', ''))} |")
    w("")
    return "\n".join(o)


def render_diagnostics():
    """docs/agent/diagnostics.md: the code registry, from `rusolve --explain all`."""
    r = subprocess.run([binary(), "--explain", "all"], capture_output=True, text=True, check=True)
    entries = json.loads(r.stdout)
    o = ["# rusolve diagnostics\n",
         "<!-- GENERATED by tools/gen_agent_docs.py from `rusolve --explain all` (the registry in "
         "crates/rusolve-core/src/diagnostic.rs). Do not edit; run the script. -->\n",
         "Every error and warning has a stable code. `rusolve --explain RSnnnn` prints an entry; under "
         "`--format json` an error is a `rusolve.diagnostics/1` document on stdout "
         "([schema](../schema/rusolve-diagnostics-1.schema.json)), the rustc-style text goes to stderr. "
         "API contract: [docs/design/diagnostics.md](../design/diagnostics.md).\n",
         "| code | severity | meaning |\n|---|---|---|"]
    for e in entries:
        o.append(f"| [{e['code']}](#{e['code'].lower()}) | {e['severity']} | {md_escape(e['title'])} |")
    o.append("")
    for e in entries:
        o.append(f"### {e['code']}\n")
        o.append(f"**{e['title']}** ({e['severity']})\n")
        o.append(e["explanation"] + "\n")
    return "\n".join(o)


def check_agent_files():
    """Problems in llms.txt, README.md and docs/skills: dead links, unknown tools or commands."""
    tools = {t["name"] for t in mcp_tools()}
    help_cmds = commands_from_help_json()
    cmds = {c["name"] for c in help_cmds}
    problems = []
    docs = [os.path.join(ROOT, "llms.txt"), os.path.join(ROOT, "README.md")]
    skills_dir = os.path.join(ROOT, "docs", "skills")
    skills = sorted(os.path.join(skills_dir, d, "SKILL.md") for d in os.listdir(skills_dir)) \
        if os.path.isdir(skills_dir) else []
    if len(skills) < 4:
        problems.append(f"docs/skills has {len(skills)} SKILL.md files, want solve, debug-infeasible, tune, extend")
    for path in docs + skills:
        rel = os.path.relpath(path, ROOT)
        if not os.path.exists(path):
            problems.append(f"{rel} is missing")
            continue
        text = open(path).read()
        if path in skills and not (text.startswith("---\nname: ") and "\ndescription: " in text.split("\n---", 1)[0]):
            problems.append(f"{rel}: frontmatter needs name and description")
        for m in re.finditer(r"mcp__rusolve__(\w+)", text):
            if m.group(1) not in tools:
                problems.append(f"{rel}: MCP tool {m.group(0)} does not exist (tools: {sorted(tools)})")
        for m in re.finditer(r"rusolve-cli (?:\.\./)?([a-z][a-z-]*)", text):
            if m.group(1) not in cmds and m.group(1) not in ("build", "mcp"):
                problems.append(f"{rel}: command `rusolve-cli {m.group(1)}` is not a rusolve subcommand")
        for m in re.finditer(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", text):
            target = m.group(1)
            if "://" in target:
                continue
            if not os.path.exists(os.path.normpath(os.path.join(os.path.dirname(path), target))):
                problems.append(f"{rel}: link target {target} does not exist")
    return problems


SKILL_EVAL_KIND = {"solve": "solve", "debug-infeasible": "debug", "tune": "tune", "extend": "extend",
                    "start-here": "class-router", "assignment-transport-flow": "class-flow",
                    "set-cover-packing": "class-cover", "scheduling": "class-scheduling",
                    "lot-sizing": "class-lotsizing", "facility-location": "class-facility",
                    "routing": "class-routing", "piecewise-semi": "class-pwl-semi", "convex-qp": "class-qp",
                    "conic": "class-conic"}


def skill_audience(skill):
    """`audience:` from a SKILL.md front matter ("" when absent)."""
    text = open(os.path.join(ROOT, "docs", "skills", skill, "SKILL.md")).read()
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    for line in (m.group(1) if m else "").split("\n"):
        if line.startswith("audience:"):
            return line.split(":", 1)[1].strip()
    return ""


def check_skill_evals():
    """Enumerate docs/skills/*/SKILL.md; every skill has an eval set (a task of its kind in
    evals/tasks, graded in graders.py), except `audience: contributor` skills, which must instead be
    left out of the user plugin (.claude-plugin/plugin.json) and of the MCP prompts (build.rs)."""
    problems = []
    sdir = os.path.join(ROOT, "docs", "skills")
    on_disk = sorted(d for d in os.listdir(sdir) if os.path.isfile(os.path.join(sdir, d, "SKILL.md")))
    contributor = [d for d in on_disk if skill_audience(d) == "contributor"]
    user = [d for d in on_disk if d not in contributor]
    plugin = json.load(open(os.path.join(ROOT, ".claude-plugin", "plugin.json"))).get("skills", [])
    want = sorted(f"./docs/skills/{d}" for d in user)
    if sorted(p.rstrip("/") for p in plugin) != want:
        problems.append(".claude-plugin/plugin.json `skills` must list exactly the non-contributor skill dirs: "
                        + ", ".join(want))
    for d in user:
        if d not in SKILL_EVAL_KIND:
            problems.append(f"docs/skills/{d}: no eval kind in SKILL_EVAL_KIND (tools/gen_agent_docs.py); "
                            "add an eval task and grader, or mark the skill `audience: contributor`")
    tasks = {}
    tdir = os.path.join(ROOT, "evals", "tasks")
    for t in sorted(os.listdir(tdir)):
        f = os.path.join(tdir, t, "task.json")
        if os.path.isfile(f):
            tasks[t] = json.load(open(f))
    graders = open(os.path.join(ROOT, "evals", "graders.py")).read()
    for skill, kind in ((s, SKILL_EVAL_KIND[s]) for s in user if s in SKILL_EVAL_KIND):
        mine = [t for t, d in tasks.items() if d.get("kind") == kind]
        if not mine:
            problems.append(f"docs/skills/{skill}: no eval task of kind `{kind}` in evals/tasks")
        for t in mine:
            if f"def grade_{t}(" not in graders:
                problems.append(f"evals/tasks/{t}: no `grade_{t}` in evals/graders.py")
            if not tasks[t].get("prompt"):
                problems.append(f"evals/tasks/{t}: task.json has no prompt")
    return problems


def check_codemap():
    """docs/agent/codemap.md is current and every AGENTS.md names real paths (tools/gen_codemap.py)."""
    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "gen_codemap.py"), "--check"],
                       capture_output=True, text=True, timeout=120)
    return r.stderr.strip().split("\n") if r.returncode != 0 else []


def main():
    text = render()
    if "--check" in sys.argv:
        bad = []
        have = open(OUT).read() if os.path.exists(OUT) else ""
        if have != text:
            bad.append("docs/agent/reference.md is stale: run `python3 tools/gen_agent_docs.py` and commit")
        have_d = open(DIAG_OUT).read() if os.path.exists(DIAG_OUT) else ""
        if have_d != render_diagnostics():
            bad.append("docs/agent/diagnostics.md is stale: run `python3 tools/gen_agent_docs.py` and commit")
        bad += check_agent_files()
        bad += check_skill_evals()
        bad += check_codemap()
        if bad:
            sys.stderr.write("\n".join(bad) + "\n")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}")
    with open(DIAG_OUT, "w") as f:
        f.write(render_diagnostics())
    print(f"wrote {DIAG_OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
